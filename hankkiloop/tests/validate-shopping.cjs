// Run with PGLITE_MODULE pointing to a locally installed @electric-sql/pglite.
const { PGlite } = require(process.env.PGLITE_MODULE || '@electric-sql/pglite')
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
;(async () => {
  const db = new PGlite()
  await db.exec(fs.readFileSync(path.join(__dirname, 'fixtures/shopping-schema.sql'), 'utf8'))
  const setup = fs.readFileSync(path.join(__dirname, '../docs/shopping_setup.sql'), 'utf8')
  await db.exec(setup)
  await db.exec(setup)
  const a = randomUUID(), b = randomUUID(), food = randomUUID(), food2 = randomUUID()
  const r1 = randomUUID(), r2 = randomUUID(), r3 = randomUUID(), p1 = randomUUID(), p2 = randomUUID()
  await db.query('insert into profiles(id) values($1),($2)', [a, b])
  await db.query("insert into food_items(id,name,base_unit) values($1,'감자','g'),($2,'양파','g')", [food, food2])
  await db.query("insert into recipes(id,title,base_servings) values($1,'감자 요리',1),($2,'감자 볶음',1),($3,'채소 볶음',1)", [r1,r2,r3])
  const asUser = async id => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]); await db.exec('set role authenticated') }
  const add = (id, recipe, items) => db.query('select hk_add_recipe_shopping($1,$2,1,$3::jsonb)', [id,recipe,JSON.stringify(items)])
  const item = (id = food, required = 100, available = 40) => ({ food_id: id, unit: 'g', required_quantity: required, available_quantity: available })
  await asUser(a)
  await add(p1,r1,[item()])
  await add(p1,r1,[item()])
  assert.equal((await db.query('select count(*)::int n from shopping_items')).rows[0].n,1)
  await assert.rejects(add(randomUUID(),r1,[item()]), /이미 장바구니/)
  await add(p2,r2,[item()])
  const rows = (await db.query('select * from shopping_items order by needed_quantity')).rows
  assert.deepEqual(rows.map(r => Number(r.needed_quantity)), [60,100])
  const first = rows[0]
  await db.query('select hk_update_shopping($1::jsonb)', [JSON.stringify([{ id:first.id,expected_count:1,count:2,selected:false }])])
  assert.equal(Number((await db.query('select planned_purchase_quantity from shopping_items where id=$1',[first.id])).rows[0].planned_purchase_quantity),120)
  await assert.rejects(db.query('select hk_update_shopping($1::jsonb)', [JSON.stringify([{ id:first.id,expected_count:1,count:3,selected:true }])]), /장바구니가 변경/)
  await asUser(b)
  assert.equal((await db.query('select count(*)::int n from shopping_items')).rows[0].n,0)
  await assert.rejects(db.query('select hk_update_shopping($1::jsonb)', [JSON.stringify([{ id:first.id,expected_count:2,remove:true }])]), /장바구니가 변경/)
  await assert.rejects(db.query('select hk_checkout_shopping($1::jsonb)', [JSON.stringify([{ shopping_item_id:first.id }])]), /찾을 수 없습니다/)
  await asUser(a)
  const purchase = { id:randomUUID(),shopping_item_id:first.id,expected_count:2,display_name:'감자',quantity:120,unit:'g',storage_type:'fridge',purchased_on:'2026-09-15',expiry_date:'2026-09-20' }
  const checkout = items => db.query('select hk_checkout_shopping($1::jsonb)', [JSON.stringify(items)])
  await assert.rejects(checkout([purchase,{...purchase,id:randomUUID(),shopping_item_id:rows[1].id,expected_count:1,expiry_date:'2026-09-01'}]), /소비기한/)
  assert.equal((await db.query('select count(*)::int n from inventory_items')).rows[0].n,0)
  assert.equal((await db.query('select count(*)::int n from shopping_items where purchased_at is not null')).rows[0].n,0)
  await checkout([purchase])
  await checkout([purchase])
  await checkout([{...purchase,id:randomUUID()}])
  assert.equal((await db.query('select count(*)::int n from inventory_items')).rows[0].n,1)
  assert.equal((await db.query('select source_shopping_item_id from inventory_items')).rows[0].source_shopping_item_id,first.id)
  assert.equal((await db.query('select food_id from inventory_items')).rows[0].food_id,food)
  assert.equal((await db.query('select count(*)::int n from inventory_dates')).rows[0].n,1)
  assert.equal((await db.query('select status from shopping_plans where id=$1',[p1])).rows[0].status,'completed')
  await db.query('select hk_update_shopping($1::jsonb)', [JSON.stringify([{ id:rows[1].id,expected_count:1,remove:true }])])
  assert.equal((await db.query('select status from shopping_plans where id=$1',[p2])).rows[0].status,'cancelled')
  await add(randomUUID(),r2,[item()])
  await assert.rejects(add(randomUUID(),r3,[{...item(),unit:'tbsp'}]), /지원하지 않는/)
  await assert.rejects(add(randomUUID(),r3,[item(food2,100,100)]), /부족한 재료가 없습니다/)
  assert.equal((await db.query('select count(*)::int n from shopping_plan_recipes where recipe_id=$1',[r3])).rows[0].n,0)
  const addChosen = (id, recipe, items) => db.query('select hk_add_recipe_ingredient_shopping($1,$2,1,$3::jsonb)', [id,recipe,JSON.stringify(items)])
  const chosenPlan = randomUUID()
  const chosenItem = { ...item(food2, 100, 100), purchase_quantity: 100 }
  await addChosen(chosenPlan, r3, [chosenItem])
  await addChosen(chosenPlan, r3, [chosenItem])
  await addChosen(randomUUID(), r3, [{ ...item(), purchase_quantity: 60 }])
  const chosenRows = (await db.query('select * from shopping_items where plan_id=$1', [chosenPlan])).rows
  assert.equal(chosenRows.length, 1)
  assert.equal(Number(chosenRows[0].planned_purchase_quantity), 100)
  assert.equal((await db.query('select count(*)::int n from shopping_plan_recipes where recipe_id=$1', [r3])).rows[0].n, 2)
  await db.exec('reset role')
  assert.equal((await db.query("select has_function_privilege('anon','hk_checkout_shopping(jsonb)','execute') as allowed")).rows[0].allowed,false)
  await asUser('')
  await assert.rejects(add(randomUUID(),r3,[item()]), /로그인이 필요/)
  await db.close()
  console.log('PASS: SQL repeatability, authenticated/RLS isolation, shared stock reservation, duplicate requests, quantity conflicts, atomic rollback, checkout retry, source links, plan lifecycle, unsupported units and anonymous denial')
})().catch(error => { console.error(error); process.exitCode=1 })
